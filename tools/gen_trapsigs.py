"""Generate harness/gen/trapsigs.h: Pascal stack signatures for every Toolbox trap and dispatcher selector.

Pascal convention: caller reserves result space, pushes args left to right; callee pops args.
Stack size per arg: 1- and 2-byte values -> 2, 4-byte values -> 4, larger records -> 4 (passed by address),
VAR parameters and pointers -> 4. Unknown types are reported and get size -1 (harness refuses to stub them).
"""
import yaml, glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', 'third_party', 'multiversal', 'defs')
items = []
for f in sorted(glob.glob(os.path.join(ROOT, '*.yaml'))):
    for it in yaml.safe_load(open(f)) or []:
        if isinstance(it, dict): items.append(it)

size = {'int8_t': 1, 'uint8_t': 1, 'char': 1, 'int16_t': 2, 'uint16_t': 2, 'int32_t': 4, 'uint32_t': 4,
        'void': 0, 'Fixed': 4, 'Fract': 4, 'int64_t': 8, 'uint64_t': 8, 'float': 4, 'double': 8}
alias = {}
for it in items:
    if 'typedef' in it: alias[it['typedef']['name']] = str(it['typedef']['type'])
    for k in ('struct', 'union'):
        if k in it and it[k].get('size') is not None: size[it[k]['name']] = it[k]['size']
    if 'enum' in it and it['enum'].get('name'): size[it['enum']['name']] = 2
    if 'funptr' in it: size[it['funptr']['name']] = 4

def tsize(t, depth=0):
    t = str(t).strip()
    if t.endswith('*') or t.endswith('&') or t.startswith('const '):
        if t.startswith('const ') and not t.endswith('*'): return tsize(t[6:])
        return 4
    if re.search(r'\[\d*\]$', t): return 4
    if t in size: return size[t]
    if t.endswith(('Ptr', 'Handle', 'Hdl', 'Hndl', 'UPP', 'ProcPtr', 'Proc', 'Ref', 'Hand', 'Pointer')): return 4
    if t in alias and depth < 20: return tsize(alias[t], depth + 1)
    if t in ('Str255', 'Str63', 'Str31', 'Str32', 'Str15', 'StringPtr', 'ConstStringPtr', 'ConstStr255Param',
             'ConstStr63Param', 'ConstStr31Param', 'ConstStr32Param', 'ConstStr15Param'): return 4
    return None

unknown = set()
def stack(t):
    s = tsize(t)
    if s is None: unknown.add(str(t)); return -1
    return 2 if s <= 2 else 4

def sig(d):
    args = d.get('args') or []
    ab = 0
    for a in args:
        if a.get('register') or (isinstance(a.get('type'), str) and 'register' in a): return None
        s = stack(a.get('type'))
        if s < 0: return (-1, 0)
        ab += s
    r = d.get('return')
    rb = 0 if not r or r == 'void' else stack(r)
    return (ab, rb)

rows, disp_rows, disp = [], [], {}
for it in items:
    if 'dispatcher' in it and 'trap' in it['dispatcher']:
        d = it['dispatcher']; disp[d['name']] = (d['trap'], d.get('selector-location', 'stack'))
for it in items:
    d = it.get('function') or it.get('procedure')
    if not d or 'name' not in d: continue
    regcall = any('register' in (a or {}) for a in (d.get('args') or [])) or 'returnreg' in d or d.get('executor_raw')
    if 'trap' in d and 'dispatcher' not in d:
        w = d['trap']
        if not (w & 0x0800): continue  # OS traps are register-based; handled by hand
        s = None if regcall else sig(d)
        ab, rb = s if s else (-1, 0)
        rows.append((w, d['name'], ab, rb))
    elif 'dispatcher' in d and d.get('selector') is not None:
        s = None if regcall else sig(d)
        ab, rb = s if s else (-1, 0)
        dn = d['dispatcher']
        if dn in disp: disp_rows.append((disp[dn][0], d['selector'], d['name'], ab, rb, disp[dn][1]))

seen = set(); out = []
out.append('/* Generated by tools/gen_trapsigs.py from multiversal. Do not edit. */')
out.append('typedef struct { unsigned short trap; const char *name; signed char argbytes; signed char retbytes; } TrapSig;')
out.append('typedef struct { unsigned short trap; unsigned long sel; const char *name; signed char argbytes; signed char retbytes; const char *loc; } SelSig;')
out.append('static const TrapSig g_trapsigs[] = {')
for w, n, ab, rb in sorted(rows):
    k = w & 0xFBFF
    if k in seen: continue
    seen.add(k)
    out.append(f'  {{0x{k:04X}, "{n}", {ab}, {rb}}},')
out.append('  {0, 0, 0, 0}\n};')
out.append('static const SelSig g_selsigs[] = {')
for w, sel, n, ab, rb, loc in sorted(disp_rows):
    out.append(f'  {{0x{w:04X}, 0x{sel:X}UL, "{n}", {ab}, {rb}, "{loc}"}},')
out.append('  {0, 0, 0, 0, 0, 0}\n};')
os.makedirs(os.path.join(HERE, '..', 'harness', 'gen'), exist_ok=True)
open(os.path.join(HERE, '..', 'harness', 'gen', 'trapsigs.h'), 'w').write('\n'.join(out) + '\n')
print(len(seen), 'toolbox traps,', len(disp_rows), 'selectors; unknown types:', len(unknown))
if '-v' in sys.argv: print(sorted(unknown))
